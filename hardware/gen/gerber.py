"""
Fabrication outputs straight from the generated geometry (no KiCad needed):
Gerber RS-274X (copper, mask, paste, silk, outline) + Excellon drill files.

Coordinates: Gerber Y axis points up, so y_out = BOARD_H - y.
Solder mask: pads +0.05 mm per side, vias tented.
"""

import math

POUR_EDGE = 0.8        # pour to board edge
POUR_CLEAR = 0.35      # pour to other-net copper
POUR_HOLE_CLEAR = 0.5  # pour to mounting holes

