def text_strokes(text, x, y, size, rot=0, anchor="center"):
    """Return list of segments for text whose cap height = size, centred at x,y (board coords)."""
    s = size / 6.0
    adv = 5.5 * s
    width = adv * len(text) - 1.5 * s
    ox = {"center": -width / 2, "left": 0.0}[anchor]
    segs = []
    a = math.radians(rot)
    for i, ch in enumerate(text.upper()):
        for line in FONT.get(ch, FONT["-"]):
            pts = []
            for gx, gy in line:
                lx = ox + i * adv + gx * s
                ly = -(gy * s - size / 2)          # board Y down
                rx = lx * math.cos(a) + ly * math.sin(a)
                ry = -lx * math.sin(a) + ly * math.cos(a)
                pts.append((x + rx, y + ry))
            if len(pts) == 1:
                pts.append(pts[0])
            for p, q in zip(pts, pts[1:]):
                segs.append((p[0], p[1], q[0], q[1]))
    return segs


class GerberWriter:
    def __init__(self, name, func, board_h):
        self.board_h = board_h
        self.ap = {}
        self.body = []
        self.lines = ["G04 Manbo carrier - generated by hardware/gen/gerber.py*",
                      "%TF.FileFunction," + func + "*%",
                      "%FSLAX46Y46*%", "%MOMM*%", "%LPD*%"]
        self.cur = None

    def _c(self, v):
        return int(round(v * 1e6))

    def aperture(self, kind, w, h=None):
        key = (kind, round(w, 4), round(h if h is not None else w, 4))
        if key not in self.ap:
            code = 10 + len(self.ap)
            if kind == "C":
                self.lines.append("%%ADD%dC,%.4f*%%" % (code, w))
            else:
                self.lines.append("%%ADD%d%s,%.4fX%.4f*%%" % (code, kind, w, h))
            self.ap[key] = code
        code = self.ap[key]
        if self.cur != code:
            self.body.append("D%d*" % code)
            self.cur = code

    def polarity(self, dark):
        self.body.append("%LPD*%" if dark else "%LPC*%")

    def region(self, pts):
        self.body.append("G36*")
        x0, y0 = pts[0]
        self.body.append("X%dY%dD02*" % (self._c(x0), self._c(self.board_h - y0)))
        for x, y in pts[1:] + [pts[0]]:
            self.body.append("X%dY%dD01*" % (self._c(x), self._c(self.board_h - y)))
        self.body.append("G37*")

    def flash(self, x, y):
        self.body.append("X%dY%dD03*" % (self._c(x), self._c(self.board_h - y)))

    def line(self, x1, y1, x2, y2):
        self.body.append("X%dY%dD02*" % (self._c(x1), self._c(self.board_h - y1)))
        self.body.append("X%dY%dD01*" % (self._c(x2), self._c(self.board_h - y2)))

    def text(self):
        return "\n".join(self.lines + ["G01*"] + self.body + ["M02*"]) + "\n"


def _pad_flash(g, pad, cx, cy, w, h, grow=0.0):
    w2, h2 = w + 2 * grow, h + 2 * grow
    if pad.shape == "circle":
        g.aperture("C", w2)
    elif pad.shape == "oval":
        g.aperture("O", w2, h2)
    else:
        g.aperture("R", w2, h2)
    g.flash(cx, cy)


def outline_segments(W, H, r=2.0, n=8):
    segs = [(r, 0, W - r, 0), (W, r, W, H - r), (W - r, H, r, H), (0, H - r, 0, r)]
    for cx, cy, a0 in ((r, r, 180), (W - r, r, 270), (W - r, H - r, 0), (r, H - r, 90)):
        for i in range(n):
            a1 = math.radians(a0 + 90 * i / n)
            a2 = math.radians(a0 + 90 * (i + 1) / n)
            segs.append((cx + r * math.cos(a1), cy + r * math.sin(a1),
                         cx + r * math.cos(a2), cy + r * math.sin(a2)))
    return segs


def build(placed, tracks, vias, W, H, via_size, via_drill, project, rev):
    files = {}
    cu = {0: GerberWriter("F_Cu", "Copper,L1,Top", H), 1: GerberWriter("B_Cu", "Copper,L2,Bot", H)}
    mask = {0: GerberWriter("F_Mask", "Soldermask,Top", H), 1: GerberWriter("B_Mask", "Soldermask,Bot", H)}
    paste = GerberWriter("F_Paste", "Paste,Top", H)
    silk = GerberWriter("F_Silkscreen", "Legend,Top", H)
    edge = GerberWriter("Edge_Cuts", "Profile,NP", H)
    pth, npth = {}, {}
    for pl in placed:
        for pad, net, cx, cy, w, h in pl.pads():
            if pad.kind == "np_thru_hole":
                npth.setdefault(round(pad.drill, 3), []).append((cx, cy))
                for L in (0, 1):
                    mask[L].aperture("C", w + 0.1)
                    mask[L].flash(cx, cy)
                continue
            layers = (0,) if pad.kind == "smd" else (0, 1)
            for L in layers:
                _pad_flash(cu[L], pad, cx, cy, w, h)
                _pad_flash(mask[L], pad, cx, cy, w, h, 0.05)
            if pad.kind == "smd":
                _pad_flash(paste, pad, cx, cy, w, h)
            else:
                pth.setdefault(round(pad.drill, 3), []).append((cx, cy))
        # silkscreen: body outline + reference
        x1, y1, x2, y2 = pl.body_abs()
        silk.aperture("C", 0.15)
        for s in ((x1, y1, x2, y1), (x2, y1, x2, y2), (x2, y2, x1, y2), (x1, y2, x1, y1)):
            silk.line(*s)
        ref = pl.part.ref
        tx, ty = (x1 + x2) / 2, y1 - 1.0
        if ty < 1.5:
            ty = y2 + 1.0
        for s in text_strokes(ref, tx, ty, 1.0):
            silk.line(*s)
        # connector pin names next to pin 1 side (assembly aid)
        if ref.startswith("J") and len(pl.part.pins) <= 6:
            names = dict(pl.part.pins)
            for pad, net, cx, cy, w, h in pl.pads():
                horiz = int(round(pl.rot)) % 180 == 90
                lx, ly = (cx, cy + 2.0) if horiz else (cx + 2.6, cy)
                for s in text_strokes(names.get(pad.num, "")[:4], lx, ly, 0.7):
                    silk.line(*s)
    for s in text_strokes("MANBO CARRIER V%s" % rev, 30.0, 88.0, 1.4, anchor="left"):
        silk.aperture("C", 0.2)
        silk.line(*s)
    # ---- copper: GND pour (solid, knock-out by clear polarity) + objects ----
    # Pad flashes above were recorded before the pour; rebuild copper layers in
    # the right order: pour -> clearances (LPC) -> all copper (LPD).
    pads_by_layer = {0: [], 1: []}
    for pl in placed:
        for pad, net, cx, cy, w, h in pl.pads():
            if pad.kind == "np_thru_hole":
                continue
            for L in ((0,) if pad.kind == "smd" else (0, 1)):
                pads_by_layer[L].append((pad, net, cx, cy, w, h))
    for L in (0, 1):
        g = GerberWriter("Cu", "Copper,L%d,%s" % (L + 1, "Top" if L == 0 else "Bot"), H)
        e = POUR_EDGE
        g.region([(e, e), (W - e, e), (W - e, H - e), (e, H - e)])
        g.polarity(False)
        for pl in placed:          # keep pour off mounting holes
            for pad, net, cx, cy, w, h in pl.pads():
                if pad.kind == "np_thru_hole":
                    g.aperture("C", w + 2 * POUR_HOLE_CLEAR)
                    g.flash(cx, cy)
        for pad, net, cx, cy, w, h in pads_by_layer[L]:
            if net != "GND":
                _pad_flash(g, pad, cx, cy, w, h, POUR_CLEAR)
        for (x1, y1, x2, y2, w, layer, net) in tracks:
            if net != "GND" and (layer == "F.Cu") == (L == 0):
                g.aperture("C", w + 2 * POUR_CLEAR)
                g.line(x1, y1, x2, y2)
        for (x, y, net) in vias:
            if net != "GND":
                g.aperture("C", via_size + 2 * POUR_CLEAR)
                g.flash(x, y)
        g.polarity(True)
        for pad, net, cx, cy, w, h in pads_by_layer[L]:
            _pad_flash(g, pad, cx, cy, w, h)
        for (x1, y1, x2, y2, w, layer, net) in tracks:
            if (layer == "F.Cu") == (L == 0):
                g.aperture("C", w)
                g.line(x1, y1, x2, y2)
        for (x, y, net) in vias:
            g.aperture("C", via_size)
            g.flash(x, y)
        cu[L] = g
    for (x, y, net) in vias:
        pth.setdefault(round(via_drill, 3), []).append((x, y))
    edge.aperture("C", 0.1)
    for s in outline_segments(W, H):
        edge.line(*s)

    base = project
    files[base + "-F_Cu.gtl"] = cu[0].text()
    files[base + "-B_Cu.gbl"] = cu[1].text()
    files[base + "-F_Mask.gts"] = mask[0].text()
    files[base + "-B_Mask.gbs"] = mask[1].text()
    files[base + "-F_Paste.gtp"] = paste.text()
    files[base + "-F_Silkscreen.gto"] = silk.text()
    files[base + "-Edge_Cuts.gm1"] = edge.text()
    files[base + "-PTH.drl"] = excellon(pth, H, plated=True)
    files[base + "-NPTH.drl"] = excellon(npth, H, plated=False)
    return files


def excellon(holes, H, plated):
    out = ["M48", "; Manbo carrier - %s holes - generated by hardware/gen/gerber.py" % ("plated" if plated else "non-plated"),
           "; #@! TF.FileFunction,%s,1,2,%s" % ("Plated" if plated else "NonPlated", "PTH" if plated else "NPTH"),
           "FMAT,2", "METRIC"]
    tools = sorted(holes)
    for i, d in enumerate(tools):
        out.append("T%dC%.3f" % (i + 1, d))
    out += ["%", "G90", "G05"]
    for i, d in enumerate(tools):
        out.append("T%d" % (i + 1))
        for x, y in holes[d]:
            out.append("X%.3fY%.3f" % (x, H - y))
    out.append("M30")
    return "\n".join(out) + "\n"
